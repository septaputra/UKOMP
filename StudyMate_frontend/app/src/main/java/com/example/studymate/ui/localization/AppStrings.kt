fun localizedUiLabel(language: String, sourceText: String): String =
    uiLabels[sourceText]?.let { appString(language, it) }
        ?: if (sourceText.startsWith("Durasi: ")) {
            "${appString(language, "duration")} ${sourceText.removePrefix("Durasi: ")}"
        } else sourceText

fun localizedFormat(language: String, key: String, vararg arguments: Any?): String =
    String.format(Locale.forLanguageTag(language), appString(language, key), *arguments)

@Composable
fun localizedUiLabel(sourceText: String): String =
    localizedUiLabel(LocalAppLanguage.current, sourceText)

@Composable
fun localizedCount(key: String, count: Int): String {
    val language = LocalAppLanguage.current
    return String.format(
        java.util.Locale.forLanguageTag(language),
        appString(language, key),
        count
    )
}

