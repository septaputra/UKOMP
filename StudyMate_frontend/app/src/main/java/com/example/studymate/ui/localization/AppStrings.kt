fun appString(language: String, key: String): String =
    scheduleUiTranslations[language.take(2)]?.get(key)
        ?: remainingUiTranslations[language.take(2)]?.get(key)
        ?: additionalTranslations[language.take(2)]?.get(key)
        ?: translations[language.take(2)]?.get(key)
        ?: translations.getValue("id")[key]
        ?: key

fun appLanguageForTag(languageTag: String): String =
    languageTag.take(2).takeIf(supportedLanguageTags::contains) ?: "id"
